"""ExamPaper Refine - server-controlled LaTeX template.

The AI model only writes the document BODY. Everything that affects
compilation and typography (document class, packages, fonts, spacing,
headers, links) is owned here so output quality never depends on the
model remembering to include packages.
"""

from __future__ import annotations

# Hardcoded preamble: modern fonts, micro-typography, generous math leading,
# clean list spacing, guaranteed page numbers, PDF bookmarks via hyperref.
LATEX_PREAMBLE = r"""% Generated by ExamPaper Refine — preamble is server-controlled.
\documentclass[11pt,a4paper]{article}

% ── Modern typography ────────────────────────────────────────────────
\usepackage[T1]{fontenc}
\usepackage[utf8]{inputenc}
\usepackage{lmodern}
\usepackage{microtype}

% ── Mathematics ──────────────────────────────────────────────────────
\usepackage{amsmath}
\usepackage{amssymb}
\usepackage{amsfonts}

% ── Layout & tables ──────────────────────────────────────────────────
\usepackage[a4paper,margin=2.2cm]{geometry}
\usepackage{graphicx}
\usepackage{array}
\usepackage{booktabs}

% ── Vector graphics (TikZ / pgfplots) ────────────────────────────────
\usepackage{tikz}
\usetikzlibrary{arrows.meta,calc,patterns,angles,quotes}
\usepackage{pgfplots}
\pgfplotsset{compat=1.18}

% ── Lists: compact, uncrowded labels ─────────────────────────────────
\usepackage{enumitem}
\setlist{itemsep=2pt,topsep=4pt,parsep=0pt}

% ── Spacing: readable math leading (fractions, superscripts) ─────────
\usepackage{setspace}
\setstretch{1.15}
\setlength{\jot}{8pt}

% ── Page numbering ───────────────────────────────────────────────────
\usepackage{fancyhdr}
\pagestyle{fancy}
\fancyhf{}
\fancyfoot[C]{\small\thepage}
\renewcommand{\headrulewidth}{0pt}

% ── Links & PDF bookmarks (navigation without colored boxes) ─────────
\usepackage[hidelinks,bookmarks=true]{hyperref}
"""

_DOCUMENT_BEGIN = r"\begin{document}"
_DOCUMENT_END = r"\end{document}"


def _extract_body(model_output: str) -> str:
    """Reduce model output to just the content between \\begin{document}
    and \\end{document}.

    Handles both compliant body-only responses (returned unchanged apart
    from stripping) and legacy full-document responses (preamble and
    wrapper removed) so the server always controls the preamble.
    """
    text = model_output.strip()
    begin_idx = text.find(_DOCUMENT_BEGIN)
    if begin_idx != -1:
        text = text[begin_idx + len(_DOCUMENT_BEGIN):]
        end_idx = text.rfind(_DOCUMENT_END)
        if end_idx != -1:
            text = text[:end_idx]
    return text.strip()


def assemble_latex_document(model_output: str) -> str:
    """Wrap the model's LaTeX in the server-controlled template."""
    body = _extract_body(model_output)
    return f"{LATEX_PREAMBLE}{_DOCUMENT_BEGIN}\n\n{body}\n\n{_DOCUMENT_END}\n"
